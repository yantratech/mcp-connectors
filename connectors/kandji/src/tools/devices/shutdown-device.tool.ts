import { KandjiUuid } from "../../helpers/kandji-id.js";
import { triggerDeviceAction } from "../../handlers/device-actions.handler.js";
import { CreateKandjiTool } from "../../helpers/create-kandji-tool.js";
import { renderToolError } from "../../helpers/format-kandji-error.js";

const ShutdownDeviceTool = CreateKandjiTool(
  "shutdown_device",
  "DISRUPTIVE: queues an MDM 'ShutDownDevice' command that powers the device off, dropping any unsaved work and active sessions. Sends POST /devices/{id}/action/shutdown. Use for confirmed loss/theft (after a lock) or to take a device offline cleanly before physical maintenance. Every successful call is logged to stderr.",
  {
    device_id: KandjiUuid.describe("The Kandji device ID"),
  },
  async ({ device_id }) => {
    const response = await triggerDeviceAction(device_id, "shutdown");
    if (response.isError) {
      return renderToolError(response);
    }
    return {
      content: [
        {
          type: "text" as const,
          text: JSON.stringify(response.result, null, 2),
        },
      ],
    };
  },
  { readOnlyHint: false, destructiveHint: false, idempotentHint: true },
);

export default ShutdownDeviceTool;
